#pragma once

// ===========================================================================
//  ZHC - Renderer/RenderSettings.h
//
//  一帧渲染用到的全局开关。
//
//  为什么单独成文件、而不是塞进 EditorUI 或 SceneRenderer：
//    它既不属于 UI，也不属于渲染器 ——
//      UI 只是"改它的人"，渲染器只是"读它的人"。
//    归属放在装配层（main），两边都只是借用一份。
//
//    如果把 gammaCorrect 塞进 EditorUI，渲染器就得反过来依赖 UI 才能
//    知道自己的设置；塞进 SceneRenderer 又会让面板需要拿到渲染器。
//    一旦出现这种"谁依赖谁"的纠结，说明这个数据本来就该由第三方持有。
// ===========================================================================
struct RenderSettings
{
	// ---- 阴影 ----
	bool ShadowEnabled = true;

	// 深度比较的偏移量，【归一化深度】[0,1]。
	// 太小 -> 表面出现条纹（acne）；太大 -> 影子从物体底部脱离（peter-panning）。
	//
	// 【PCSS 的两个阶段都用它，单位是一致的】blocker search 里会乘 4 作为余量 ——
	// 那一遍误判的代价不是 acne，而是"把接收面自己的纹素当成遮挡物"：
	// 平均遮挡深度被拉向接收面 → 半影塌缩 → 阴影反而更硬。
	// 那个症状和"PCSS 完全没生效"一模一样，难查得多，所以多留余量
	float ShadowBias = 0.0002f;

	// 过滤半径的【上限】，单位 = 纹素。<= 0 退化成单次采样的硬边（用来做 A/B 对比）。
	//
	// 【它不是 blocker search 的搜索窗口】搜索窗口是固定的
	//（见 PCSS.glsl 里的 BLOCKER_SEARCH_RADIUS），两者职责不同：
	//   搜索窗口  决定"能找到多远的遮挡物"
	//   这个上限  决定"半影最多糊到什么程度"
	//
	// 拖大了噪点会明显：泊松盘只有 32 个样本，撒得越开空隙越大
	int FilterRadius = 10;
	

	// PCSS 的"光源视半径"比例，控制整体软度。
	//
	// 平行光在无穷远，没有真实的"光源尺寸 / 距离"之比，所以这是美术旋钮，
	// 不是物理量 —— 拖它就是在选"影子能软到什么程度"。
	// 换算链（见 PCSS.glsl）：
	//   半影(纹素) = 归一化深度差 × (far - near) × 这个值 ÷ 一个纹素的世界尺寸
	//   取 0.05 时：遮挡物离接收面约 0.6 世界单位 -> 半影约 4 纹素
	float ShadowLightSize = 0.05f;

	// 光照相机的取景范围 —— 这一对必须一起调：
	//   太小 -> 场景有部分落在视锥外，那部分不出阴影
	//   太大 -> 正交投影的深度范围被摊薄，精度下降，acne 变严重
	float Near = 0.1f;
	float ShadowExtent   = 4.0f;   // 正交投影的半宽半高
	float ShadowDistance = 12.0f;   // 光照相机离场景中心多远

	// 后处理开关。
	//
	// 【它取代了原来的 GammaCorrect】"输出前要不要编码成 sRGB" 这件事
	// 现在整个是后处理 pass 的一部分了。留两个做同一件事的开关，
	// 早晚会出现"两个都关了但画面还是那样"这种查不出原因的状态。
	//
	// 【它不是审美开关】关掉之后看到的是【线性值直接当 sRGB 显示】：
	// 中间调明显偏暗、整体发灰。留着它是当一张体检表 ——
	// 后处理链路哪里出错，关掉它就能立刻分开
	// "问题在后面的后处理"还是"问题在前面的场景 pass"
	bool PostProcessEnabled = true;

	// 曝光。【这个默认值是标定过的，不是随手填的】
	//
	// ACES 是按"18% 灰 = 中间调"设计的，而本场景典型受光面（平台）
	// 的线性亮度约 1.06 —— 比标准场景亮约 2.5 档。
	// 所以 0.2 x 1.06 = 0.21，正好落回 0.18 附近。
	//
	// 【1.0 的含义只是"不做任何调整"】它永远中性 —— 画面偏白说明
	// 场景本身太亮，不是曝光设错了。它是"相机的进光量"，不是亮度滑块
	float Exposure = 0.2f;

	//色调映射模式
	int TonemapMode = 1;
	int DebugHDRView = 0; // 1 = 只显示亮度 > 1.0 的像素
	// -------bloom-------
	bool BloomEnabled = true;

	// 亮度阈值：多亮才算"在发光"。
	//
	// 【重要：它作用在"曝光之后"的亮度上】—— BloomDownsample.glsl 里
	// 先乘 u_Exposure 再和它比。所以改 Exposure 会连带改变"谁在发光"：
	//     曝光 0.2 + 阈值 0.25 -> 平台(0.21)不发光，球的高光(0.44)发光  ✓
	//     曝光 0.2 + 阈值 1.00 -> 什么都不发光（阈值高于场上所有值）
	// 后者是"Bloom 莫名其妙消失了"最常见的原因，不是 bug。
	// 经验法则：阈值 ≈ 最亮的"不该发光"表面的曝光后亮度 x 1.2
	float BloomThreshold = 0.25f;

	// 软过渡宽度。knee = 0 会退化成硬阈值（光晕边缘出现断层）
	float BloomKnee = 0.25f;
	//叠回去的倍率
	float BloomStrength = 0.6f;
	// 升采样帐篷滤波的扩散倍数。
	// 【和"一级 + 拉大抽头间距"那种做法的区别在这一项上】——
	// 金字塔下"覆盖范围"是靠级数往下走的，不是靠拉间距，
	// 所以它只要 1.0 左右就够，调大反而会出现同心环
	float BloomRadius = 1.0f;
	// 逐级衰减。每往上一级乘一次，所以第 k 级的贡献是 scatter^k。
	//   1.0  -> 各级等权，得到一团均匀的雾
	//   0.7  -> 近处紧、远处散（推荐）
	float BloomScatter = 0.7f;
	// 【最值得拖的一个】用几级金字塔。
	//   1 级 -> 紧贴高光的一圈边
	//   5 级 -> 完整的多尺度光晕
	// 拖它就能直观看出"级数"在做什么：加一级 = 光晕往外扩一圈
	int   BloomLevels = 5;

	//----FXAA -----
	bool FxaaEnabled = true;
	// 相对阈值：亮度差超过 "最大亮度 × 这个值" 才算边。
	//   调大 -> 只有很硬的边才处理（保守，几乎看不出变化）
	//   调小 -> 更多渐变被当成边（画面整体变糊）
	// 0.063 是官方给的"中等质量"推荐值
	float FxaaEdgeThreshold = 0.063f;
	// 绝对阈值：整块亮度差低于它就完全跳过。
	// 它管的是暗处 —— 暗处的相对阈值会自动变得极小，
	// 没有这一项的话影子里会先糊起来
	float FxaaEdgeThresholdMin = 0.0312f;
	// 只显示"边界掩码"，用来确认 FXAA 到底在哪些地方动手
	int DebugEdges = 0;

	// =======================================================================
	//  调试图层
	//
	//  把 Scene 面板切换到任意一张中间纹理上。
	//
	//  【为什么值得单独做一件事】管线有五六张中间图，而"画面对"和
	//  "管线接对"是两个不同的问题。没有这个开关时你只能看到最后那张 ——
	//  一旦它不对，你分不清是场景 pass 错了、还是后处理哪一环错了。
	//
	//  实战价值：定位"FBO 完整、绑定正确、无 GL 错误，但面板全黑"那种
	//  静默 bug 时，把 sceneBuffer 直接贴出来一步就能把范围砍一半 ——
	//  那个 bug 之前耗掉了很多轮，正是因为看不到中间状态
	// =======================================================================
	enum DebugViewKind
	{
		DebugOff = 0,
		DebugSceneColor,     // sceneBuffer 的颜色（线性 HDR，未曝光未色调映射）
		DebugSceneDepth,     // sceneBuffer 的深度附件
		DebugShadowDepth,    // shadowMap（2048x2048）
		DebugBloomL0,        // 辉光金字塔第 0 级（阈值提取 + 上采样累积之后）
		DebugPostOutput,     // postProcessBuffer（已曝光 + 色调映射 + gamma）
		DebugViewCount,
	};

	// 【main 里的 switch 用这些常量，不要用裸数字】
	// 名字表在 EditorUI.cpp 里，靠一个 static_assert 钉住数量一致
	int DebugView = DebugOff;
};
