#pragma once

// ===========================================================================
//  ZHC - Renderer/RenderSettings.h
//
//  一帧渲染用到的全局开关。
//
//  为什么单独成文件、而不是塞进 EditorUI 或 SceneRenderer：
//    它既不属于 UI，也不属于渲染器 ——
//      UI 只是"改它的人"，渲染器只是"读它的人"。
//    归属放在装配层（main），两边都只是借用一份。
//
//    如果把 gammaCorrect 塞进 EditorUI，渲染器就得反过来依赖 UI 才能
//    知道自己的设置；塞进 SceneRenderer 又会让面板需要拿到渲染器。
//    一旦出现这种"谁依赖谁"的纠结，说明这个数据本来就该由第三方持有。
// ===========================================================================
struct RenderSettings
{
	// 输出前是否做"线性 -> sRGB"编码。
	// 关掉是为了能实时对比"在线性空间算完再编码"和"直接把线性值当 sRGB 输出"
	bool GammaCorrect = true;
};
